"""Build supplementary.tex (Tables S1-S9) from results/r2.json,
results/r4.json and results/real_results_secondary.json. No numbers are typed by hand.
Run from the package root: python scripts/make_supplementary.py"""
import json
from pathlib import Path
R = Path(__file__).resolve().parents[1]
d = json.loads((R / "results/r2.json").read_text())
rt = json.loads((R / "results/r2_runtime.json").read_text())
NM = {"empirical": "Empirical", "certified": "Overall-cert.", "selective_certified": "Selective-cert.",
      "sgr_confidence": "SGR (FNR)"}


def row(x):
    if x is None:
        return r"\multicolumn{4}{c}{not certified}"
    return (f"{x['retained_fn']}/{x['retained_pos']} & [{100*x['ci95'][0]:.1f}, {100*x['ci95'][1]:.1f}] & "
            f"{100*(1-x['coverage']):.1f} & {100*x['retained_fpr']:.1f}")


o = [r"""\documentclass[11pt]{article}
\usepackage[margin=2cm]{geometry}\usepackage{booktabs}\usepackage{times}\usepackage{caption}
\title{Supplementary material for ``Risk-Controlled Selective Prediction for AI Decision Services under Degraded Data Quality''}
\date{}\begin{document}\maketitle
\sloppy All values are outputs of \texttt{scripts/run\_ictx\_r2.py} and
\texttt{scripts/run\_ictx\_r4.py} (fixed seeds); this file is generated by
\texttt{scripts/make\_supplementary.py}. Miss = retained misses / retained
positives; CI = exact 95\% Clopper--Pearson; Abst.\ = abstention (\%);
FPR = false-positive rate among retained negatives (\%). $\alpha=0.05$,
$\delta=0.10$.

\begin{table}[h]\centering\caption*{Table S1. Band half-width $m$ (clinical testbed, moderate MCAR, test fold, 97 positives).}
\begin{tabular}{llcccc}\toprule $m$ & Rule & Miss & CI & Abst. & FPR\\\midrule"""]
for m, v in d["E3_band"].items():
    for k in ["empirical", "certified", "selective_certified"]:
        o.append(f"{float(m):.2f} & {NM[k]} & {row(v[k])}\\\\")
    o.append(r"\midrule")
o[-1] = r"\bottomrule\end{tabular}\end{table}"
o.append(r"""\begin{table}[h]\centering\caption*{Table S2. Fifty independent re-splits (clinical testbed). Runs $>$5\% = runs whose test-fold retained FNR exceeded the target.}
\begin{tabular}{llcccccc}\toprule Level & Rule & Certified runs & Runs $>$5\% & Max FNR & Pooled miss [CI] & Abst. & FPR\\\midrule""")
for lv, v in d["E4_resplits50"].items():
    for k, x in v.items():
        if x["n_certified"] == 0:
            o.append(f"{lv} & {NM[k]} & 0/50 & \\multicolumn{{5}}{{c}}{{not certified in any run}}\\\\")
        else:
            o.append(f"{lv} & {NM[k]} & {x['n_certified']}/50 & {x['runs_above_target']} & {100*x['fnr_max']:.1f} & "
                     f"{x['pooled_fn']}/{x['pooled_pos']} [{100*x['pooled_ci95'][0]:.1f}, {100*x['pooled_ci95'][1]:.1f}] & "
                     f"{100*x['abstention_mean']:.1f} & {100*x['fpr_mean']:.1f}\\\\")
o.append(r"\bottomrule\end{tabular}\end{table}")
w = d["E5_wdbc"]
o.append(r"""\begin{table}[h]\centering\caption*{Table S3. Wisconsin Diagnostic Breast Cancer (scikit-learn; """
         + f"{w['n']} cases, {w['n_pos']} malignant; split {w['split'][0]}/{w['split'][1]}/{w['split'][2]}, {w['test_pos']} test positives). "
         + r"""Noise in feature-SD units; MNAR as in the main text. Base: threshold 0.5, no abstention.}
\begin{tabular}{llcccc}\toprule Setting & Rule & Miss & CI & Abst. & FPR\\\midrule""")
for nm in ["clean", "mcar_moderate", "mcar_severe", "mnar_moderate"]:
    lab = nm.replace("_", " ")
    for k in ["base", "empirical", "certified", "selective_certified"]:
        o.append(f"{lab} & {NM.get(k, 'Base')} & {row(w[nm][k])}\\\\")
    o.append(r"\midrule")
o[-1] = r"\bottomrule\end{tabular}\end{table}"
r4 = json.loads((R / "results/r4.json").read_text())
r6 = r4["F6_runtime"]
o.append(r"""\begin{table}[h]\centering\caption*{Table S4. Runtime (\texttt{run\_ictx\_r4.py}): one thread, """
         + f"{r6['warmup']} warm-up and {r6['reps']} timed calls; CPU {r6['cpu']}, Python {r6['python']}, scikit-learn {r6['sklearn']}."
         + r"""}
\begin{tabular}{lr}\toprule Quantity & Value\\\midrule
"""
         + f"Calibration, 99-point grid & {r6['calibration_ms']:.1f} ms\\\\\n"
         + f"Random forest, one query (median) & {r6['rf_single_ms_median']:.1f} ms\\\\\n"
         + f"Gate, one query (median) & {r6['gate_single_us_median']:.1f} $\\mu$s\\\\\n"
         + f"Random forest, 285 queries (median) & {r6['rf_batch285_ms_median']:.1f} ms\\\\\n"
         + f"Random forest per query in that batch & {r6['rf_per_query_in_batch_us']:.0f} $\\mu$s\\\\\n"
         + f"Gate, 285 queries (vectorised, median) & {r6['gate_batch285_us_median']:.1f} $\\mu$s\\\\\n"
         + f"Gate state & {r6['state_bytes']} bytes\\\\\n"
         + r"\bottomrule\end{tabular}\end{table}")
o.append(r"""\paragraph{Baselines at severe MCAR.} SGR: """ + ("not certified" if d["E2_baselines_severe"]["sgr_confidence"] is None else "certified")
         + r"""; Mondrian conformal: """ + row(d["E2_baselines_severe"]["mondrian_conformal"]).replace("&", ",")
         + r""" (no abstention).""")
iot = json.loads((R / "results/real_results_secondary.json").read_text())
c = iot["cohort"]
o.append(r"""\begin{table}[h]\centering\caption*{Table S5. Second synthetic domain: """ + iot["domain"]
         + f" ({c['n']} machines, {c['n_features']} features, prevalence {c['prevalence']:.2f}; split "
         + f"{iot['split']['train']}/{iot['split']['cal']}/{iot['split']['test']}; seed {c['seed']}). "
         + r"""Empirical rule only (\texttt{run\_eval\_secondary.py}); with about 75 test positives these estimates are coarse, and base FNR did not rise with degradation, so this is a weak test.}
\begin{tabular}{lccccc}\toprule MCAR level & Mask rate & $\hat\tau$ & Base FNR & Retained FNR & Abst.\\\midrule""")
for x in iot["ablation_mcar"]:
    o.append(f"{x['level']} & {x['rate']:.2f} & {x['tau']:.2f} & {100*x['base_fnr']:.1f} & "
             f"{100*x['retained_fnr_test']:.1f} & {100*x['abstention']:.1f}\\\\")
o.append(r"\bottomrule\end{tabular}\end{table}")

NMR = {"empirical": "Empirical", "certified": "Overall-cert.", "selective_certified": "Selective-cert."}
F1 = r4["F1_pool_resplits50"]
o.append(r"""\begin{table}[h]\centering\caption*{Table S6. External-pool truth (\texttt{run\_ictx\_r4.py}). """
         + f"Pool: {r4['pool']['n']} fresh simulated patients ({r4['pool']['positives']} positives), degraded once per setting. "
         + r"""For each of 50 re-splits (new split and forest seed) the rule's threshold, calibrated on the full or half calibration fold, is evaluated on the pool. Exceed = runs whose true retained FNR $>5\%$; mean/max true retained FNR, mean abstention and mean retained FPR in \%.}
\small\begin{tabular}{lllcccccc}\toprule Setting & Cal. & Rule & Cert. & Exceed & Mean & Max & Abst. & FPR\\\midrule""")
for st, v in F1.items():
    for cal in ["full", "half"]:
        for k in ["empirical", "certified", "selective_certified"]:
            x = v[f"{cal}/{k}"]
            o.append(f"{st} & {cal} & {NMR[k]} & {x['n_certified']}/50 & {x['true_exceed']} & {100*x['true_rfnr_mean']:.1f} & "
                     f"{100*x['true_rfnr_max']:.1f} & {100*x['abstention_mean']:.1f} & {100*x['fpr_mean']:.1f}\\\\")
    for k, lab in [("sgr_binary", "SGR (binary search)"), ("sgr_fixed", "SGR (fixed seq.)")]:
        o.append(f"{st} & full & {lab} & {v[k]['n_certified']}/50 & \\multicolumn{{5}}{{c}}{{not certified}}\\\\"
                 if v[k]["n_certified"] == 0 else f"{st} & full & {lab} & {v[k]['n_certified']}/50 & {v[k]['true_exceed']} & & & & \\\\")
    o.append(r"\midrule")
o[-1] = r"\bottomrule\end{tabular}\end{table}"
CN = ["Sepsis", "ARDS", "ACS"]
o.append(r"""\begin{table}[h]\centering\caption*{Table S7. Subgroups of the external pool: true retained FNR of the selective-certified rule pooled over 50 re-splits (retained misses / retained positives, exact 95\% CI).}
\begin{tabular}{llccc}\toprule Setting & Condition & Misses/positives & rFNR (\%) & 95\% CI\\\midrule""")
for st, v in r4["F5_subgroups_selective"].items():
    for x in v:
        o.append(f"{st} & {CN[x['condition']]} & {x['misses']}/{x['retained_pos']} & {100*x['rfnr']:.1f} & "
                 f"[{100*x['ci95'][0]:.1f}, {100*x['ci95'][1]:.1f}]\\\\")
    o.append(r"\midrule")
o[-1] = r"\bottomrule\end{tabular}\end{table}"
o.append(r"""\begin{table}[h]\centering\caption*{Table S8. Calibration shift (seed-42 split, test fold): threshold calibrated on one setting and deployed on another.}
\begin{tabular}{llcccc}\toprule Calibrated $\rightarrow$ deployed & Rule & Miss & CI & Abst. & FPR\\\midrule""")
for k, v in r4["F4_calibration_shift"].items():
    for rr in ["empirical", "selective_certified"]:
        lab = k.replace("->", " $\\rightarrow$ ")
        o.append(f"{lab} & {NMR[rr]} & {row(v[rr])}\\\\")
o.append(r"\bottomrule\end{tabular}\end{table}")
F3 = r4["F3_baselines_moderate"]
o.append(r"""\begin{table}[h]\centering\caption*{Table S9. Moderate MCAR, test fold. Top: confidence ranking at the coverage of each LTT rule, labelled at 0.5 or centred on that rule's $\hat\tau$, and split conformal (LAC, $\alpha=0.05$, singletons retained). Bottom: sensitivity to $\delta$.}
\begin{tabular}{llcccc}\toprule Method & Coverage of & Miss & CI & Abst. & FPR\\\midrule""")
for k in ["empirical", "certified", "selective_certified"]:
    o.append(f"Confidence, label 0.5 & {NMR[k]} & {row(F3['softmax_at_0.5/' + k])}\\\\")
    o.append(f"Confidence, centred on $\\hat\\tau$ & {NMR[k]} & {row(F3['softmax_at_tau/' + k])}\\\\")
o.append(f"Split conformal & -- & {row(F3['split_conformal'])}\\\\\\midrule")
for dl, v in F3["delta_sensitivity"].items():
    for rr in ["certified", "selective_certified"]:
        o.append(f"$\\delta={dl}$ & {NMR[rr]} ($\\hat\\tau={v[rr]['tau']:.2f}$) & {row(v[rr])}\\\\")
o.append(r"\bottomrule\end{tabular}\end{table}\end{document}")
(R / "supplementary.tex").write_text("\n".join(o), encoding="utf-8")
print("ok")
